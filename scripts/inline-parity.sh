# Check that every function musl 1.2.6 can inline is also available as a
# static inline definition in keel's headers.  keel may expose extra inline
# functions; it must never expose fewer than musl.
#
# -fkeep-inline-functions makes the compiler emit every static inline
# definition even when unused, so nm gives the real inlinable set instead of a
# textual guess.  Each public header is compiled on its own so feature guards
# and per-header includes are honoured.  The three headers that only wrap
# kernel UAPI (sys/kd.h, sys/soundcard.h, sys/vt.h) are skipped: they define
# no inlines and pulling in <linux/...> would make the check depend on the
# host's kernel headers.
#
# The check is C-only: musl's headers only *remove* inlines in C++ mode
# (`__isspace`, the ctype predicates), never add any, so the C set is a
# superset of the C++ set.
#
# musl headers are generated by scripts/musl-headers.sh; the same
# KEEL_MUSL_CACHE / KEEL_MUSL_INC_ROOT overrides as macro-parity.sh apply.
#
# The five architectures are independent, so run them in parallel and print
# their logs in a stable order.  Each arch uses its own object/error files.

set -euo pipefail

export LC_ALL=C

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
source "$ROOT/scripts/musl-headers.sh"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

extract() {
    local inc="$1" cc="$2" nm_tool="$3" out="$4" work="$5"
    local header rel err="$work/compile.err" obj="$work/obj.o"
    : > "$out"
    while IFS= read -r header; do
        rel="${header#"$inc"/}"
        case "$rel" in
            sys/kd.h|sys/soundcard.h|sys/vt.h) continue ;;
        esac
        if ! printf '#include <%s>\n' "$rel" |
            "$cc" -std=gnu11 -D_GNU_SOURCE -nostdinc -I "$inc" \
                -O0 -fkeep-inline-functions \
                -x c -c -o "$obj" - 2>"$err"; then
            echo "error: cannot compile header '$rel' with $cc:" >&2
            tail -n 5 "$err" >&2
            return 1
        fi
        # Keep C identifiers only; loongarch64 nm also reports local labels
        # such as "L0\001" as local text symbols.
        "$nm_tool" --defined-only "$obj" |
            awk -v header="$rel" '$2 ~ /^[tT]$/ && $3 ~ /^[A-Za-z_][A-Za-z0-9_]*$/ { print $3 "\t" header }'
    done < <(find "$inc" -name '*.h' ! -path '*/bits/*' -print | sort) >> "$out"
}

check_arch() {
    local arch="$1"
    local work="$tmp/$arch"
    local musl_all="$work/musl" keel_all="$work/keel"
    local missing extra musl_count keel_count extra_count name header

    mkdir -p "$work"
    extract "$MUSL_INC_ROOT/$arch/include" "${MUSL_CC[$arch]}" "${MUSL_NM[$arch]}" "$musl_all" "$work" || return 1
    extract "$ROOT/include" "${MUSL_CC[$arch]}" "${MUSL_NM[$arch]}" "$keel_all" "$work" || return 1

    sort -u "$musl_all" -o "$musl_all"
    cut -f1 "$musl_all" | sort -u > "$work/musl-names"
    cut -f1 "$keel_all" | sort -u > "$work/keel-names"

    missing="$(comm -23 "$work/musl-names" "$work/keel-names")"
    extra="$(comm -13 "$work/musl-names" "$work/keel-names")"
    musl_count=$(wc -l < "$work/musl-names")
    keel_count=$(wc -l < "$work/keel-names")
    extra_count=$(printf '%s\n' "$extra" | sed '/^$/d' | wc -l)

    if [ -z "$missing" ]; then
        echo "$arch: musl=$musl_count keel=$keel_count (+$extra_count extra), no missing inline functions"
        return 0
    fi

    echo "$arch: musl=$musl_count keel=$keel_count, missing inline functions:" >&2
    printf '%s\n' "$missing" | while IFS= read -r name; do
        header="$(awk -v n="$name" '$1 == n { print $2; exit }' "$musl_all")"
        echo "  $name (via $header)" >&2
    done
    return 1
}

pids=()
for arch in "${MUSL_ARCHES[@]}"; do
    (
        if check_arch "$arch" > "$tmp/$arch.log" 2>&1; then
            rc=0
        else
            rc=$?
        fi
        printf '%s\n' "$rc" > "$tmp/$arch.rc"
        exit 0
    ) &
    pids+=("$!")
done

for pid in "${pids[@]}"; do
    wait "$pid" || true
done

status=0
for arch in "${MUSL_ARCHES[@]}"; do
    cat "$tmp/$arch.log"
    rc="$(cat "$tmp/$arch.rc" 2>/dev/null || echo 1)"
    if [ "$rc" -ne 0 ]; then
        status=1
    fi
done

exit "$status"
